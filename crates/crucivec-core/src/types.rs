use serde::{Deserialize, Serialize};

/// Identifies the mutation or search operation associated with a benchmark ticket.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum QueryType {
    /// Vector similarity search with top-K candidate requirement and optional filter predicate.
    Search {
        k: usize,
        filter: Option<FilterPredicate>,
    },
    /// Insertion or replacement of a vector embedding with an assigned document ID.
    Upsert {
        id: u64,
    },
    /// Hard removal of a vector embedding by ID (HNSW tombstone generation).
    Delete {
        id: u64,
    },
}

/// Stratified modulo filter predicate used to calibrate selectivity cohorts.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum FilterPredicate {
    /// High selectivity cohort (~60% pass rate: `id % 10 in [0..5]`).
    High {
        modulo: u64,
        allowed_remainders: Vec<u64>,
    },
    /// Medium selectivity cohort (~10% pass rate: `id % 10 == 0`).
    Medium {
        modulo: u64,
        target_remainder: u64,
    },
    /// Needle-in-a-haystack cohort (~0.1% pass rate: `id % 1000 == 42`).
    Needle {
        modulo: u64,
        target_remainder: u64,
    },
}

impl FilterPredicate {
    /// Evaluates whether a given document ID satisfies the filter predicate.
    #[inline(always)]
    pub fn matches(&self, id: u64) -> bool {
        match self {
            Self::High { modulo, allowed_remainders } => {
                let rem = id % modulo;
                allowed_remainders.contains(&rem)
            }
            Self::Medium { modulo, target_remainder } => (id % modulo) == *target_remainder,
            Self::Needle { modulo, target_remainder } => (id % modulo) == *target_remainder,
        }
    }
}

/// Dispatch ticket generated by the hardware pacer containing planned schedule timestamps.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DispatchTicket {
    /// Monotonically increasing sequence number.
    pub seq_id: u64,
    /// Absolute timestamp in nanoseconds when this ticket was intended to be emitted.
    pub scheduled_emit_ns: u64,
    /// Targeted query or mutation payload type.
    pub query_type: QueryType,
}

/// Supported vector distance and similarity metrics.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum DistanceMetric {
    DotProduct,
    Euclidean,
    Cosine,
}

/// Collection configuration schema for vector database initialization.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CollectionSchema {
    pub name: String,
    pub dimension: usize,
    pub metric: DistanceMetric,
}

/// Vector record snapshot container.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VectorRecord {
    pub id: u64,
    pub vector: Vec<f32>,
    pub lsn: u64,
}

